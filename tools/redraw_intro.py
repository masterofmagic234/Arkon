  subprocess.run(['ffmpeg','-v','error','-y','-framerate',str(fps),'-i',str(dest/'%04d.png'),'-an','-c:v','libx264','-crf','17','-preset','medium','-pix_fmt','yuv420p','-movflags','+faststart',str(OUT/(CLIPS[clip-1]+'.mp4'))],check=True)
