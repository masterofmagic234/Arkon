def build_key(k,frames):
 x,y,w,h=k['bbox'];dx,dy=SHIFTS[k['name']]
 full=frames[k['frame']].copy().astype(np.float32)
 style=cv2.resize(cv2.imread(str(K/k['style'])),(w,h),interpolation=cv2.INTER_AREA)
 # Rigid registration corrects small crop/head displacement introduced by the
 # image editor. Keep a generous union of the original and edited silhouette.
 M=np.float32([[1,0,dx],[0,1,dy]])
 # Register the new painted head against original low-frequency anatomy,
 # independently of background edits. The result is one rigid crop transform.
 style=cv2.warpAffine(style,M,(w,h),flags=cv2.INTER_CUBIC,borderMode=cv2.BORDER_REFLECT_101)
 mask=np.zeros((h,w),np.uint8);pts=np.array(POLY[k['name']],np.int32)
 cv2.fillPoly(mask,[pts],255)
 sm=cv2.warpAffine(mask,M,(w,h),flags=cv2.INTER_LINEAR)
 region=cv2.max(mask,sm)
 def roto(image):
  labels=np.full((h,w),cv2.GC_BGD,np.uint8)
  outer=cv2.dilate(region,np.ones((7,7),np.uint8))>0
  labels[outer]=cv2.GC_PR_BGD;labels[region>0]=cv2.GC_PR_FGD
  core=cv2.erode(region,np.ones((25,25),np.uint8))>0
  labels[core]=cv2.GC_FGD
  cv2.grabCut(image,labels,None,np.zeros((1,65),np.float64),np.zeros((1,65),np.float64),4,cv2.GC_INIT_WITH_MASK)
  return np.isin(labels,[cv2.GC_FGD,cv2.GC_PR_FGD]).astype(np.uint8)*255
 source_crop=frames[k['frame']][y:y+h,x:x+w]
 mask=cv2.max(roto(style),roto(source_crop))
 if k['name']=='01-072':cv2.ellipse(mask,(78,105),(33,30),0,0,360,255,-1)
