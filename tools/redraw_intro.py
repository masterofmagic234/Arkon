 grays=[cv2.cvtColor(v[ry:ry+rh,rx:rx+rw],cv2.COLOR_BGR2GRAY) for v in frames]
 prev_flow={i:dis.calc(grays[i],grays[i-1],None) for i in range(1,len(frames))}
 next_flow={i:dis.calc(grays[i],grays[i+1],None) for i in range(len(frames)-1)}
 def to_key(i,f):
  mx=gx.copy();my=gy.copy()
  direction=-1 if f<i else 1
  flows=prev_flow if direction==-1 else next_flow
  for cur in range(i,f,direction):
   q=flows[cur]
   fx=cv2.remap(q[:,:,0],mx,my,cv2.INTER_LINEAR,borderMode=cv2.BORDER_REPLICATE)
   fy=cv2.remap(q[:,:,1],mx,my,cv2.INTER_LINEAR,borderMode=cv2.BORDER_REPLICATE)
   mx+=fx;my+=fy
  return mx,my
 stats=[];started=time.monotonic()
 hd_cap=cv2.VideoCapture(str(R/(CLIPS[clip-1]+'.mp4')))
 for i,original in enumerate(frames):
  ok,original_hd=hd_cap.read();assert ok
  original_hd=cv2.resize(original_hd,(1920,1080),interpolation=cv2.INTER_CUBIC)
  if keyonly and i not in [k['config']['frame'] for k in keys]:continue
  target=original[ry:ry+rh,rx:rx+rw];gray=cv2.cvtColor(target,cv2.COLOR_BGR2GRAY)
  # Broadly nearest pose; state filter only applies when another key with
