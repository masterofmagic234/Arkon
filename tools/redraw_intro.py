  raw=[]
  for k in ranked:
   f=k['config']['frame'];dense_x,dense_y=to_key(i,f)
   A=np.float32([[1,0,0],[0,1,0]]);tracked=0
   if i!=f:
    # Forward tracking of the original head gives a coherent silhouette,
    # including during newly uncovered background or a blurred eye rub.
    fx,fy=to_key(f,i)
    valid=(k['track_mask']>0)
    sy,sx=np.where(valid);take=np.arange(0,len(sx),max(1,len(sx)//1500))
    if len(take)>=8:
     old=np.stack([sx[take],sy[take]],axis=1).astype(np.float32)
     new=np.stack([fx[sy[take],sx[take]],fy[sy[take],sx[take]]],axis=1)
     fit,inliers=cv2.estimateAffinePartial2D(old,new,method=cv2.RANSAC,ransacReprojThreshold=2,maxIters=1000,confidence=.995)
     if fit is not None and .65<np.linalg.norm(fit[0,:2])<1.6:
      A=fit.astype(np.float32);tracked=int(inliers.sum())
   inv=cv2.invertAffineTransform(A)
   ax=inv[0,0]*gx+inv[0,1]*gy+inv[0,2]
   ay=inv[1,0]*gx+inv[1,1]*gy+inv[1,2]
   # Preserve a coherent head silhouette. Only a bounded smooth correction
   # from the original dense motion may deform the new face internally.
   dx=cv2.GaussianBlur(np.clip(dense_x-ax,-2,2),(0,0),2)
   dy=cv2.GaussianBlur(np.clip(dense_y-ay,-2,2),(0,0),2)
   mx=ax+dx;my=ay+dy
   sty=cv2.remap(k['style'],mx,my,cv2.INTER_CUBIC,borderMode=cv2.BORDER_REFLECT_101)
   alpha=cv2.remap(k['alpha'],ax,ay,cv2.INTER_LINEAR,borderMode=cv2.BORDER_CONSTANT)
   src=cv2.remap(k['source'],mx,my,cv2.INTER_LINEAR,borderMode=cv2.BORDER_REFLECT_101)
   # Warped original/key similarity suppresses a poor pose correspondence.
   error=cv2.GaussianBlur(np.mean(np.abs(src.astype(np.float32)-target),axis=2),(0,0),3)
   dist=abs(i-f);weight=np.full_like(error,1.0/(dist+1.0)**4)
   if i==f:weight*=10000
   raw.append((sty,alpha,weight,k['config']['name']))
  assert len(raw)==1
  # One actual pose is tracked at a time, with no translucent duplicate head.
  k=ranked[0]
  mx_hd=(cv2.resize(mx,(825,713),interpolation=cv2.INTER_LINEAR)+.5)*1.875-.5
