  if i>0:
   speed=float(np.median(np.linalg.norm(prev_flow[i],axis=2)[raw[0][1]>.85]))

  else:speed=0.
  result=original_hd.copy()
  target_hd=original_hd[75:788,:825]
  result[75:788,:825]=np.clip(edited*alpha[:,:,None]+target_hd*(1-alpha[:,:,None]),0,255).astype(np.uint8)
  assert np.array_equal(result[:,825:],original_hd[:,825:])
